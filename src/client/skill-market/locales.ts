export type SkillMarketLocale = keyof typeof skillMarketMessages
export type SkillMarketKey = keyof typeof skillMarketMessages['zh-CN']

/** Resolve locale tag to skill-market dictionary accessor. */
export function skillMarketT(locale: string | undefined): (key: SkillMarketKey) => string {
  const tag: SkillMarketLocale = locale?.startsWith('zh') ? 'zh-CN' : 'en-US'
  const dict = skillMarketMessages[tag]
  return key => dict[key]
}

export function skillMarketLocaleParam(locale: string | undefined): string {
  return locale?.startsWith('zh') ? 'zh-CN' : 'en-US'
}
